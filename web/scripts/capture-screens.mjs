// Captures the screens in the landing page's product tour from the small sample hotel as it comes, in both languages:
//   public/screens/<today|booking|calendar>-<locale>.png        laptop view, 1280x800 at 2x
//   public/screens/<today|booking|calendar>-phone-<locale>.png  phone view, 390x844 at 2x
//   src/site/content/tourSpots.ts                                where each numbered point sits on the laptop view
//
//   npm run build && npx vite preview --port 4173 &      (the built app must be running)
//   PW_CHROMIUM=/path/to/chromium node scripts/capture-screens.mjs
//   python3 scripts/prepare-resources.py --screens       (PNG -> WebP, sized for the page)
//
// Run it again when the app's look changes.
import { mkdirSync, writeFileSync } from 'node:fs'
import { launch, open, out, show, signIn } from './capture-common.mjs'

/** The screens, in tab order, and what each numbered point on them shows (matches tour.items[].points in the copy). */
const SCREENS = [
  {
    key: 'today',
    path: '/app',
    spots: [
      (p) => p.locator('.ds-booking__money small').first(), // what an arrival still owes
      (p) => p.locator('.ds-booking__actions').nth(1), // check in (on the second arrival, so the points don't touch)
      (p) => p.locator('.ds-staying__badges > *').first(), // report not sent
    ],
  },
  {
    key: 'booking',
    path: '/app/bookings/current',
    spots: [
      (p) => p.locator('main h2').filter({ hasText: /check-in/i }).first(), // the check-in record
      (p) => p.locator('section[aria-labelledby="care-title"] button').first(), // one-tap care log
      (p) => p.locator('section[aria-labelledby="payments-title"] .ds-money, section[aria-labelledby="payments-title"]').first(), // paid and left
    ],
  },
  {
    key: 'calendar',
    path: '/app/calendar',
    spots: [
      (p) => p.locator('.ds-cal__head .is-today').first(), // tonight
      async (p) => { // an empty day, about halfway down
        const free = p.locator('.ds-cal__free')
        return free.nth(Math.floor((await free.count()) * 0.55))
      },
      (p) => p.locator('.ds-cal__bar').nth(1), // a taken cage
    ],
  },
]

mkdirSync(out, { recursive: true })
const spots = {}
const browser = await launch()
for (const locale of ['en', 'id']) {
  spots[locale] = {}
  for (const phone of [false, true]) {
    const { context, page } = await open(browser, locale, { phone, scale: 2 })
    await signIn(page, 'sample')
    const { width, height } = page.viewportSize()
    for (const s of SCREENS) {
      await show(page, s.path)
      await page.screenshot({ path: `${out}${s.key}${phone ? '-phone' : ''}-${locale}.png` })
      if (phone) continue
      // each point in % of the screen, just left of what it marks so it never covers it; null when off the screen
      spots[locale][s.key] = []
      for (const find of s.spots) {
        const box = await (await find(page)).boundingBox().catch(() => null)
        const x = box && Math.max(box.x - 14, 14)
        const y = box && box.y + box.height / 2
        const seen = box && x > 0 && x < width && y > 0 && y < height
        if (!seen) console.warn(`  ${locale} ${s.key}: a point is off the screen`)
        spots[locale][s.key].push(seen ? { x: +((x / width) * 100).toFixed(1), y: +((y / height) * 100).toFixed(1) } : null)
      }
    }
    console.log(`${phone ? 'phone' : 'laptop'} ${locale}`)
    await context.close()
  }
}
await browser.close()

writeFileSync(
  new URL('../src/site/content/tourSpots.ts', import.meta.url),
  `// Generated by scripts/capture-screens.mjs: where each numbered point of the product tour sits on its laptop screen,
// in % of the screen (null: not on the screen). Captured with the screens; don't edit by hand.
export type TourSpot = { x: number; y: number } | null;

export const tourSpots: Record<"en" | "id", Record<string, TourSpot[]>> = ${JSON.stringify(spots, null, 2)};
`,
)
console.log('tourSpots.ts')
